using Microsoft.Extensions.Options;

namespace Torii.Api.Services;

/// <summary>File storage options, bound to the "Storage" configuration section.</summary>
public class FileStorageOptions
{
    /// <summary>Root folder of stored files, absolute or relative to the content root.</summary>
    public string Path { get; set; } = "storage/files";

    /// <summary>Maximum size of one uploaded file, in megabytes.</summary>
    public int MaxFileSizeMb { get; set; } = 25;

    public long MaxFileSizeBytes => MaxFileSizeMb * 1024L * 1024L;
}

/// <summary>Stores file contents under opaque keys generated by the app.</summary>
public interface IFileStorage
{
    /// <summary>Writes <paramref name="content"/> and returns its new storage key.</summary>
    Task<string> SaveAsync(Stream content, CancellationToken ct = default);

    /// <summary>Opens a stored file for reading.</summary>
    Stream OpenRead(string key);

    /// <summary>Deletes a stored file (no-op when missing).</summary>
    void Delete(string key);
}

/// <summary>
/// Disk storage: files live under <see cref="FileStorageOptions.Path"/>, as
/// <c>yyyy/MM/{guid}</c>. Keys never come from user input, and are still checked to stay
/// inside the root folder.
/// </summary>
public sealed class DiskFileStorage : IFileStorage
{
    private readonly string _root;

    public DiskFileStorage(IOptions<FileStorageOptions> options, IWebHostEnvironment env)
    {
        _root = System.IO.Path.GetFullPath(System.IO.Path.Combine(env.ContentRootPath, options.Value.Path));
        Directory.CreateDirectory(_root);
    }

    public async Task<string> SaveAsync(Stream content, CancellationToken ct = default)
    {
        // Year and month formatted separately: "/" inside a date format is the culture's date separator.
        var now = DateTime.UtcNow;
        var key = $"{now:yyyy}/{now:MM}/{Guid.NewGuid():N}";
        var path = Resolve(key);
        Directory.CreateDirectory(System.IO.Path.GetDirectoryName(path)!);

        await using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None);
        await content.CopyToAsync(file, ct);
        return key;
    }

    public Stream OpenRead(string key)
        => new FileStream(Resolve(key), FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true);

    public void Delete(string key)
    {
        var path = Resolve(key);
        if (File.Exists(path))
            File.Delete(path);
    }

    private string Resolve(string key)
    {
        var path = System.IO.Path.GetFullPath(System.IO.Path.Combine(_root, key));
        if (!path.StartsWith(_root + System.IO.Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new InvalidOperationException("Invalid storage key.");
        return path;
    }
}
