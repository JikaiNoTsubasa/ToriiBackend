using Microsoft.EntityFrameworkCore;
using Torii.Api.Models;

namespace Torii.Api.Data;

/// <summary>
/// Torii EF Core context. Add the business data model DbSets here.
/// </summary>
public class ToriiDbContext(DbContextOptions<ToriiDbContext> options) : DbContext(options)
{
    public DbSet<User> Users => Set<User>();
    public DbSet<RefreshToken> RefreshTokens => Set<RefreshToken>();
    public DbSet<Ticket> Tickets => Set<Ticket>();
    public DbSet<TicketChannel> TicketChannels => Set<TicketChannel>();
    public DbSet<ChannelParticipant> ChannelParticipants => Set<ChannelParticipant>();
    public DbSet<Customer> Customers => Set<Customer>();
    public DbSet<TicketEdge> TicketEdges => Set<TicketEdge>();
    public DbSet<TicketMessage> TicketMessages => Set<TicketMessage>();
    public DbSet<StoredFile> StoredFiles => Set<StoredFile>();
    public DbSet<ChannelFile> ChannelFiles => Set<ChannelFile>();
    public DbSet<TicketActivity> TicketActivities => Set<TicketActivity>();

    /// <summary>Ticket number sequence (TI000001, TI000002…).</summary>
    public const string TicketNumberSequence = "TicketNumbers";

    /// <summary>SQL function formatting the next number, created by the AddTicket migration.</summary>
    public const string TicketNumberFunction = "next_ticket_number";

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        base.OnModelCreating(modelBuilder);

        modelBuilder.Entity<User>(entity =>
        {
            entity.HasIndex(u => u.Email).IsUnique();
            entity.Property(u => u.Email).HasMaxLength(256);
            entity.Property(u => u.DisplayName).HasMaxLength(128);
            entity.Property(u => u.Position).HasMaxLength(128);
            entity.Property(u => u.AccountType).HasDefaultValue(AccountType.APPLICATION);
        });

        modelBuilder.Entity<RefreshToken>(entity =>
        {
            entity.HasIndex(t => t.Token).IsUnique();
            entity.HasOne(t => t.User)
                  .WithMany(u => u.RefreshTokens)
                  .HasForeignKey(t => t.UserId)
                  .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.HasSequence<long>(TicketNumberSequence);

        modelBuilder.Entity<Ticket>(entity =>
        {
            entity.HasKey(t => t.Number);
            // Generated by the database: concurrency-safe (sequence), unique (primary key).
            entity.Property(t => t.Number)
                  .HasMaxLength(16)
                  .HasDefaultValueSql($"{TicketNumberFunction}()")
                  .ValueGeneratedOnAdd();
            entity.HasMany(t => t.Channels)
                .WithOne(t => t.Ticket)
                .HasForeignKey(t => t.TicketNumber)
                .OnDelete(DeleteBehavior.Cascade);
            // Restrict: users are soft-deleted, so the creator stays referenced.
            entity.HasOne(t => t.CreatedBy)
                  .WithMany()
                  .HasForeignKey(t => t.CreatedById)
                  .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<Customer>(entity =>
        {
            entity.HasMany(c => c.Members)
                  .WithMany(u => u.Customers)
                  .UsingEntity<Dictionary<string, object>>(
                      "CustomerMembers",
                      j => j.HasOne<User>().WithMany().HasForeignKey("UserId").OnDelete(DeleteBehavior.Cascade),
                      j => j.HasOne<Customer>().WithMany().HasForeignKey("CustomerId").OnDelete(DeleteBehavior.Cascade),
                      j =>
                      {
                          j.HasKey("CustomerId", "UserId");
                          j.HasIndex("UserId"); // visibility query: "customers of the user"
                      });
        });

        modelBuilder.Entity<ChannelParticipant>(entity =>
        {
            entity.HasKey(p => new { p.TicketChannelId, p.CustomerId });
            entity.HasIndex(p => p.CustomerId);

            entity.HasOne(p => p.TicketChannel)
                  .WithMany(ch => ch.Participants)
                  .HasForeignKey(p => p.TicketChannelId)
                  .OnDelete(DeleteBehavior.Cascade);

            // Restrict: a customer still taking part in a ticket cannot be deleted.
            entity.HasOne(p => p.Customer)
                  .WithMany(c => c.ChannelParticipations)
                  .HasForeignKey(p => p.CustomerId)
                  .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<TicketEdge>(entity =>
        {
            entity.ToTable(t => t.HasCheckConstraint(
                "CK_TicketEdges_DifferentCustomers", "\"SourceCustomerId\" <> \"TargetCustomerId\""));

            // One live edge per direction; soft-deleted edges do not block re-creation.
            entity.HasIndex(e => new { e.SourceCustomerId, e.TargetCustomerId })
                  .IsUnique()
                  .HasFilter("\"IsDeleted\" = false");
            entity.HasIndex(e => e.TargetCustomerId);

            entity.HasOne(e => e.SourceCustomer)
                  .WithMany()
                  .HasForeignKey(e => e.SourceCustomerId)
                  .OnDelete(DeleteBehavior.Restrict);
            entity.HasOne(e => e.TargetCustomer)
                  .WithMany()
                  .HasForeignKey(e => e.TargetCustomerId)
                  .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<TicketMessage>(entity =>
        {
            entity.HasIndex(m => new { m.TicketChannelId, m.CreatedAt });

            entity.HasOne(m => m.TicketChannel)
                  .WithMany(ch => ch.Messages)
                  .HasForeignKey(m => m.TicketChannelId)
                  .OnDelete(DeleteBehavior.Cascade);

            // Restrict: a user who authored messages cannot be hard-deleted.
            entity.HasOne(m => m.Author)
                  .WithMany()
                  .HasForeignKey(m => m.AuthorId)
                  .OnDelete(DeleteBehavior.Restrict);

            // Forward: the copy survives the hard deletion of the original's channel (link cleared).
            entity.HasOne(m => m.ForwardedFrom)
                  .WithMany()
                  .HasForeignKey(m => m.ForwardedFromId)
                  .OnDelete(DeleteBehavior.SetNull);
        });

        modelBuilder.Entity<StoredFile>(entity =>
        {
            entity.HasIndex(f => f.StorageKey).IsUnique();
            entity.Property(f => f.StorageKey).HasMaxLength(256);
            entity.Property(f => f.FileName).HasMaxLength(255);
            entity.Property(f => f.ContentType).HasMaxLength(255);
        });

        modelBuilder.Entity<ChannelFile>(entity =>
        {
            // A file is linked once per channel (soft-deleted links do not block re-adding it).
            entity.HasIndex(cf => new { cf.TicketChannelId, cf.StoredFileId })
                  .IsUnique()
                  .HasFilter("\"IsDeleted\" = false");
            entity.HasIndex(cf => cf.StoredFileId);

            entity.HasOne(cf => cf.TicketChannel)
                  .WithMany(ch => ch.Files)
                  .HasForeignKey(cf => cf.TicketChannelId)
                  .OnDelete(DeleteBehavior.Cascade);
            // Restrict: the stored file outlives its links (it may be linked to other channels).
            entity.HasOne(cf => cf.StoredFile)
                  .WithMany(f => f.ChannelLinks)
                  .HasForeignKey(cf => cf.StoredFileId)
                  .OnDelete(DeleteBehavior.Restrict);
        });

        modelBuilder.Entity<TicketActivity>(entity =>
        {
            entity.HasIndex(a => new { a.TicketChannelId, a.CreatedAt });

            entity.HasOne(a => a.TicketChannel)
                  .WithMany(ch => ch.Activities)
                  .HasForeignKey(a => a.TicketChannelId)
                  .OnDelete(DeleteBehavior.Cascade);
            entity.HasOne(a => a.Actor)
                  .WithMany()
                  .HasForeignKey(a => a.ActorId)
                  .OnDelete(DeleteBehavior.Restrict);
            entity.HasOne(a => a.ChannelFile)
                  .WithMany()
                  .HasForeignKey(a => a.ChannelFileId)
                  .OnDelete(DeleteBehavior.SetNull);
        });

        // Always last: covers the enums of every entity declared above.
        modelBuilder.UseUpperCaseEnumStrings();
    }
}
