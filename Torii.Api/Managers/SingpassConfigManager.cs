using Microsoft.EntityFrameworkCore;
using Torii.Api.Data;
using Torii.Api.Dtos;
using Torii.Api.Exceptions;
using Torii.Api.Models;
using Torii.Api.Services.Singpass;

namespace Torii.Api.Managers;

/// <summary>
/// Singpass settings (single row, created on first access). Enabling requires a complete
/// configuration (client id, redirect URI, keys). Private keys are generated here and never
/// leave the server: administrators only see their ids, Singpass reads the public JWKS.
/// </summary>
public class SingpassConfigManager(
    ToriiDbContext db,
    SingpassClient singpass,
    IConfiguration configuration,
    IHostEnvironment environment,
    ILogger<SingpassConfigManager> logger) : ToriManager(db)
{
    /// <summary>Issuer of a local mock, honoured in Development only.</summary>
    private string? IssuerOverride => environment.IsDevelopment() ? configuration["Singpass:IssuerOverride"] : null;

    /// <summary>Current settings (tracked), created with the defaults when missing.</summary>
    public async Task<SingpassConfig> GetAsync(CancellationToken ct = default)
    {
        var config = await _dbContext.SingpassConfigs.FirstOrDefaultAsync(c => c.Id == SingpassConfig.SingletonId, ct);
        if (config is null)
        {
            config = new SingpassConfig();
            _dbContext.SingpassConfigs.Add(config);
            await _dbContext.SaveChangesAsync(ct);
        }
        config.IssuerOverride = IssuerOverride;
        return config;
    }

    public async Task<SingpassConfigDto> GetDtoAsync(CancellationToken ct = default) => ToDto(await GetAsync(ct));

    public async Task<SingpassConfigDto> UpdateAsync(SingpassConfigUpdateRequest request, long actorId, CancellationToken ct = default)
    {
        var config = await GetAsync(ct);
        var errors = new Dictionary<string, string[]>();

        var clientId = string.IsNullOrWhiteSpace(request.ClientId) ? null : request.ClientId.Trim();
        var redirectUri = string.IsNullOrWhiteSpace(request.RedirectUri) ? null : request.RedirectUri.Trim();
        var scopes = string.Join(' ', request.Scopes.Split(' ', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries));

        if (!scopes.Split(' ').Contains("openid"))
            errors["scopes"] = ["The scopes must include \"openid\"."];
        if (redirectUri is not null && !IsValidRedirectUri(redirectUri))
            errors["redirectUri"] = ["Use an absolute https URL (http is only allowed for localhost)."];

        if (request.Enabled)
        {
            if (clientId is null) errors["clientId"] = ["Required to enable Singpass."];
            if (redirectUri is null) errors.TryAdd("redirectUri", ["Required to enable Singpass."]);
            if (config.SigningKeyJwk is null || config.EncryptionKeyJwk is null)
                errors["keys"] = ["Generate the keys before enabling Singpass."];
        }
        if (errors.Count > 0)
            throw new ValidationException(errors);

        config.Enabled = request.Enabled;
        config.Environment = request.Environment;
        config.ClientId = clientId;
        config.RedirectUri = redirectUri;
        config.Scopes = scopes;
        config.UpdatedAt = DateTime.UtcNow;
        config.UpdatedById = actorId;
        await _dbContext.SaveChangesAsync(ct);

        logger.LogInformation("Singpass settings updated by user {ActorId} (enabled: {Enabled}, {Environment}).",
            actorId, config.Enabled, config.Environment);
        return ToDto(config);
    }

    /// <summary>
    /// New signing + encryption keys. The previous ones stop working at once, so the JWKS must
    /// be re-read by Singpass (it caches it up to an hour): rotate outside busy hours.
    /// </summary>
    public async Task<SingpassConfigDto> GenerateKeysAsync(long actorId, CancellationToken ct = default)
    {
        var config = await GetAsync(ct);
        var now = DateTime.UtcNow;
        config.SigningKeyJwk = SingpassKeys.Generate("sig", now);
        config.EncryptionKeyJwk = SingpassKeys.Generate("enc", now);
        config.KeysGeneratedAt = now;
        config.UpdatedAt = now;
        config.UpdatedById = actorId;
        await _dbContext.SaveChangesAsync(ct);

        logger.LogWarning("Singpass keys regenerated by user {ActorId}.", actorId);
        return ToDto(config);
    }

    /// <summary>Public JWKS to register with Singpass (null while no key was generated).</summary>
    public async Task<object?> GetPublicJwksAsync(CancellationToken ct = default)
    {
        var config = await GetAsync(ct);
        if (config.SigningKeyJwk is null || config.EncryptionKeyJwk is null)
            return null;
        return new
        {
            keys = new[]
            {
                SingpassKeys.Parse(config.SigningKeyJwk).Public,
                SingpassKeys.Parse(config.EncryptionKeyJwk).Public,
            },
        };
    }

    /// <summary>Reads the discovery document of the selected environment.</summary>
    public async Task<SingpassTestResultDto> TestAsync(CancellationToken ct = default)
    {
        var m = await singpass.GetMetadataAsync(await GetAsync(ct), ct);
        return new SingpassTestResultDto(m.Issuer, m.AuthorizationEndpoint, m.PushedAuthorizationRequestEndpoint,
            m.TokenEndpoint, m.JwksUri);
    }

    private static bool IsValidRedirectUri(string value)
        => Uri.TryCreate(value, UriKind.Absolute, out var uri) &&
           (uri.Scheme == Uri.UriSchemeHttps || (uri.Scheme == Uri.UriSchemeHttp && uri.IsLoopback));

    private static SingpassConfigDto ToDto(SingpassConfig c) => new(
        c.Enabled, c.Environment, c.Issuer, c.ClientId, c.RedirectUri, c.Scopes,
        c.SigningKeyJwk is null ? null : SingpassKeys.Parse(c.SigningKeyJwk).Kid,
        c.EncryptionKeyJwk is null ? null : SingpassKeys.Parse(c.EncryptionKeyJwk).Kid,
        c.KeysGeneratedAt, c.IsConfigured, c.UpdatedAt);
}
